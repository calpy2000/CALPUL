// Generalized version of merge-new-batch.js — combines the established
// answers.js (days 1-N, already finalized) with ANY number of draft batch
// logs (new-batch2-log.json, new-batch3-log.json, ...) still sitting
// un-merged past day N, applies a removal set spanning any of those
// ranges, and compacts survivors into one fresh gap-free 1..N sequence.
//
// Only includes batch-log entries with status 'ok' (failed fetches never
// got an image file in the first place, so there's nothing to include).
//
// Usage: node merge-all-batches.js 282,283,284,...

const fs = require('fs');
const path = require('path');

const IMAGES_DIR = path.join(__dirname, '..', '..', 'games', 'muveez', 'images');
const ANSWERS_PATH = path.join(__dirname, '..', '..', 'games', 'muveez', 'answers.js');
const STAGING_DIR = path.join(__dirname, 'renumber-staging');

function readCurrentAnswers() {
  const src = fs.readFileSync(ANSWERS_PATH, 'utf8');
  const match = src.match(/export const ANSWERS_366 = \[([\s\S]*)\];/);
  const titles = [];
  match[1].split('\n').forEach((line) => {
    const m = line.match(/^\s*'((?:[^'\\]|\\.)*)',/);
    if (m) titles.push(m[1].replace(/\\'/g, "'")); // only push on an actual match
  });
  return titles;
}

function main() {
  const removeSet = new Set((process.argv[2] || '').split(',').map((s) => parseInt(s.trim(), 10)).filter((n) => !isNaN(n)));
  console.log(`Removing ${removeSet.size} day(s): ${[...removeSet].sort((a, b) => a - b).join(', ')}`);

  const mainTitles = readCurrentAnswers();
  const allDays = mainTitles.map((title, i) => ({ day: i + 1, title }));

  // Pick up every new-batch*-log.json file in this folder, in numeric order,
  // so this stays generic across however many rounds have happened.
  const logFiles = fs.readdirSync(__dirname)
    .filter((f) => /^new-batch\d*-log\.json$/.test(f))
    .sort((a, b) => {
      const na = parseInt((a.match(/(\d+)/) || ['0'])[0], 10);
      const nb = parseInt((b.match(/(\d+)/) || ['0'])[0], 10);
      return na - nb;
    });
  console.log('Reading batch logs:', logFiles.join(', '));

  logFiles.forEach((f) => {
    const entries = JSON.parse(fs.readFileSync(path.join(__dirname, f), 'utf8'));
    entries.forEach((e) => {
      if (e.status === 'ok') allDays.push({ day: e.dayNumber, title: e.display });
    });
  });

  allDays.sort((a, b) => a.day - b.day);

  const survivors = allDays.filter((d) => !removeSet.has(d.day));
  console.log(`Survivors: ${survivors.length} (was ${allDays.length})`);

  fs.rmSync(STAGING_DIR, { recursive: true, force: true });
  fs.mkdirSync(STAGING_DIR, { recursive: true });

  survivors.forEach((s, i) => {
    const newDay = i + 1;
    fs.copyFileSync(path.join(IMAGES_DIR, `${s.day}.jpg`), path.join(STAGING_DIR, `${newDay}.jpg`));
  });

  const maxOldDay = Math.max(...allDays.map((d) => d.day));
  for (let day = 1; day <= maxOldDay; day++) {
    const p = path.join(IMAGES_DIR, `${day}.jpg`);
    if (fs.existsSync(p)) fs.unlinkSync(p);
  }
  survivors.forEach((s, i) => {
    const newDay = i + 1;
    fs.renameSync(path.join(STAGING_DIR, `${newDay}.jpg`), path.join(IMAGES_DIR, `${newDay}.jpg`));
  });
  fs.rmSync(STAGING_DIR, { recursive: true, force: true });

  const lines = survivors.map((s, i) => {
    const day = i + 1;
    const escaped = s.title.replace(/'/g, "\\'");
    return `  '${escaped}', // day ${day}: ${s.title}`;
  });

  const fileContent = `// Auto-generated by tools/muveez-curation/merge-all-batches.js — do not hand-edit.
// One answer per calendar day-of-year, same indexing as images/<day>.jpg
// (see index.js's dayOfYear() usage).
export const ANSWERS_366 = [
${lines.join('\n')}
];
`;
  fs.writeFileSync(ANSWERS_PATH, fileContent);
  console.log(`Done. answers.js now has ${survivors.length} entries (days 1-${survivors.length}).`);
}

main();
